import { test, expect as baseExpect, _electron as electron } from '@playwright/test';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
const expect = baseExpect.configure({ timeout: 20000 });
const executablePath = resolve(`out/Poliscope-${process.platform}-${process.arch}/poliscope${process.platform === 'win32' ? '.exe' : ''}`);

test('WP-028 packaged keyboard discovery full source choices preview history and retained context', async () => {
  test.setTimeout(150000);
  const directory = await mkdtemp(join(tmpdir(), 'poliscope-atlas-ui-'));
  const worlds = join(directory, 'worlds'); await mkdir(worlds);
  const env: Record<string, string | undefined> = { ...process.env, POLISCOPE_USER_DATA: join(directory, 'app') };
  delete env.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ executablePath, args: ['--no-sandbox', ...(process.platform === 'linux' && !process.env.DISPLAY ? ['--ozone-platform=headless', '--headless', '--disable-gpu'] : [])], env: env as Record<string, string> });
  try {
    const page = await app.firstWindow();
    await expect(page.getByRole('status')).toHaveText('Local engine ready');
    await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }); }, worlds);
    await page.getByRole('button', { name: 'Choose sandbox folder' }).press('Enter');
    await page.getByLabel('Civilization name', { exact: true }).fill('Atlas society');
    await page.getByRole('button', { name: 'Create sandbox', exact: true }).press('Enter');
    await expect(page.getByRole('cell', { name: 'Unknown', exact: true })).toHaveCount(2);
    await page.getByRole('button', { name: 'Decision atlas', exact: true }).focus();
    await page.keyboard.press('Enter');
    const atlas = page.getByRole('region', { name: 'Decision discovery' });
    await expect(atlas).toContainText('36 matching questions');
    await atlas.getByRole('button', { name: 'Next atlas page' }).focus(); await page.keyboard.press('Enter');
    await expect(atlas.getByRole('button', { name: 'Previous atlas page' })).toBeEnabled();
    await atlas.getByLabel('Search full questions and alternatives').fill('nutrition-complete');
    await expect(atlas).toContainText('1 matching questions');
    await atlas.getByRole('button', { name: /^DEC-001 ·/ }).focus(); await page.keyboard.press('Enter');
    const detail = atlas.getByRole('region', { name: 'Atlas question' });
    await expect(detail.locator('ol > li')).toHaveCount(4);
    await expect(detail).toContainText("Player's choice: Unanswered");
    await expect(detail).toContainText('Source historical status: adopted');
    await detail.getByRole('button', { name: /^Inspect source/ }).press('Enter');
    await expect(detail.getByRole('region', { name: 'Archived source' })).toContainText('9ff539997dbd1bd3fa99deabcf6bc5907602df60');
    await detail.getByRole('button', { name: 'Open interview and preview' }).focus(); await page.keyboard.press('Enter');
    await expect(page.getByRole('region', { name: 'Selected domain' })).toBeFocused();
    const interview = page.getByRole('region', { name: 'Domain interview' });
    await expect(interview.getByRole('radio')).toHaveCount(5);
    await interview.getByRole('radio').nth(3).focus(); await page.keyboard.press('Space');
    await interview.getByRole('button', { name: 'Preview draft', exact: true }).focus(); await page.keyboard.press('Enter');
    await page.getByRole('button', { name: 'Apply draft', exact: true }).focus(); await page.keyboard.press('Enter');
    await expect(page.getByText('Applied one design revision.', { exact: false })).toBeAttached();
    await atlas.getByLabel('Player selection').selectOption('selected');
    await expect(atlas).toContainText('1 matching questions');
    await atlas.getByRole('button', { name: /^DEC-001 ·/ }).press('Enter');
    await expect(detail).toContainText('Retained original alternatives');
    await expect(detail).toContainText("Player's choice: society:DEC-001/option/D");
    await detail.getByRole('button', { name: 'Open history for this state' }).focus(); await page.keyboard.press('Enter');
    await expect(page.getByRole('region', { name: 'Design history' })).toBeAttached();
    await page.getByRole('button', { name: 'Decision atlas', exact: true }).press('Enter');
    await expect(atlas.getByLabel('Search full questions and alternatives')).toHaveValue('nutrition-complete');
    await expect(atlas.getByLabel('Player selection')).toHaveValue('selected');
    await atlas.getByLabel('Search full questions and alternatives').fill('no matching canary');
    await expect(atlas).toContainText('No matching questions.');
  } finally { await app.close(); await rm(directory, { recursive: true, force: true }); }
});
