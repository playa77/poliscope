import { test, expect as baseExpect, _electron as electron } from '@playwright/test';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
const expect = baseExpect.configure({ timeout: 20000 });
const executablePath = resolve(`out/Poliscope-${process.platform}-${process.arch}/poliscope${process.platform === 'win32' ? '.exe' : ''}`);

test('E2E-002.c persisted goals and private notes preserve physics, historical classification and active deletion', async () => {
  test.setTimeout(180000);
  const directory = await mkdtemp(join(tmpdir(), 'poliscope-evidence-ui-'));
  const worlds = join(directory, 'worlds'); await mkdir(worlds);
  const env: Record<string,string | undefined> = { ...process.env, POLISCOPE_USER_DATA: join(directory, 'app') }; delete env.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ executablePath, args: ['--no-sandbox'], env: env as Record<string,string> });
  try {
    const page = await app.firstWindow(); await expect(page.getByRole('status')).toHaveText('Local engine ready');
    await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }); }, worlds);
    await page.getByRole('button', { name: 'Choose sandbox folder' }).press('Enter');
    await page.getByLabel('Civilization name').fill('Evidence inquiry');
    await page.getByRole('button', { name: 'Create sandbox', exact: true }).press('Enter');
    await page.getByRole('button', { name: 'Evidence and models', exact: true }).press('Enter');
    const view = page.getByRole('region', { name: 'Evidence and models workspace' });
    await view.getByLabel('Inspect evidence').selectOption('notes');
    await expect(view).toContainText('No recorded notes');
    await view.getByRole('button', { name: 'Add private inquiry or note' }).press('Enter');
    await expect(page.getByRole('button', { name: 'History and comparison', exact: true })).toBeDisabled();
    await view.getByLabel('Private note kind').selectOption('expectation');
    await view.getByLabel('Private note text').fill('PRIVATE_OLD_CANARY: I expect no numerical social effects');
    await view.getByRole('button', { name: 'Preview evidence edit' }).press('Enter');
    await expect(view.getByRole('region', { name: 'Evidence edit preview' })).toContainText('Physical result unchanged');
    expect(await page.evaluate(async () => {
      const context = (await window.poliscope.workspaceCatalogue()).branches[0].context;
      return (await window.poliscope.workbench({ context, scope_id: 'home', collection: 'notes' })).items.length;
    })).toBe(0);
    await view.getByRole('button', { name: 'Apply evidence edit' }).press('Enter');
    await expect(view.getByRole('table')).toContainText('PRIVATE_OLD_CANARY');
    const first = await page.evaluate(async () => (await window.poliscope.workspaceCatalogue()).branches[0].context);
    await view.getByRole('button', { name: /^Edit private note / }).press('Enter');
    await view.getByLabel('Private note kind').selectOption('observation');
    await view.getByLabel('Private note text').fill('PRIVATE_NEW_CANARY: qualitative inquiry remains qualitative');
    await view.getByRole('button', { name: 'Preview evidence edit' }).press('Enter');
    await view.getByRole('button', { name: 'Apply evidence edit' }).press('Enter');
    await expect(view.getByRole('table')).toContainText('PRIVATE_NEW_CANARY');
    await view.getByRole('button', { name: 'Add declared goal or target' }).press('Enter');
    await view.getByLabel('Declared goal question').fill('What would change my interpretation?');
    await view.getByLabel('Goal ID').fill('inquiry:goal');
    await view.getByRole('button', { name: 'Preview evidence edit' }).press('Enter');
    await expect(view.getByRole('region', { name: 'Evidence edit preview' })).toContainText('ordinary goal content');
    await expect(view.getByRole('region', { name: 'Evidence edit preview' })).toContainText('Physical result unchanged');
    await view.getByRole('button', { name: 'Apply evidence edit' }).press('Enter');
    await expect(page.getByText('1 declared goals · 0 selected policies · 0 registered mechanisms')).toBeVisible();
    await view.getByLabel('Inspect evidence').selectOption('goals');
    await expect(view.getByRole('table')).toContainText('What would change my interpretation?');
    await page.getByRole('button', { name: 'Civilization overview', exact: true }).press('Enter');
    await page.getByText('Distributions, accounts and commitments', { exact: true }).press('Enter');
    await page.getByLabel('Retained collection').selectOption('goals');
    await expect(page.getByRole('article')).toContainText('What would change my interpretation?');
    await page.getByRole('button', { name: 'Evidence and models', exact: true }).press('Enter');
    await expect(page.getByRole('combobox', { name: 'Scope', exact: true })).toBeEnabled();
    await page.getByLabel('Read a retained revision').fill(first.revision_id);
    await page.getByLabel('Read a retained revision').press('Enter');
    await view.getByLabel('Inspect evidence').selectOption('notes');
    await expect(view.getByRole('table')).toContainText('PRIVATE_OLD_CANARY');
    await expect(view.getByRole('button', { name: /^Edit private note / })).toHaveCount(0);
    await view.getByRole('button', { name: /^Delete all active versions of private note / }).press('Enter');
    await expect(view.getByRole('table')).toContainText('deleted');
    await expect(view).not.toContainText('PRIVATE_OLD_CANARY');
    await expect(page.getByRole('combobox', { name: 'Scope', exact: true })).toBeEnabled();
    await page.getByLabel('Read a retained revision').fill('');
    await page.getByLabel('Read a retained revision').press('Enter');
    await view.getByLabel('Inspect evidence').selectOption('notes');
    await expect(view.getByRole('table')).toContainText('deleted');
    await expect(view).not.toContainText('PRIVATE_NEW_CANARY');
    await view.getByRole('button', { name: 'Compare branches and assumptions' }).press('Enter');
    await expect(page.getByRole('heading', { name: 'History and comparison', exact: true })).toBeVisible();
    await page.screenshot({ path: '/tmp/poliscope-evidence.png', fullPage: true });
  } finally { await app.close(); await rm(directory, { recursive: true, force: true }); }
});
