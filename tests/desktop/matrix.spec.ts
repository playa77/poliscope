import { test, expect as baseExpect, _electron as electron } from '@playwright/test';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
const expect = baseExpect.configure({ timeout: 20000 });
const executablePath = resolve(`out/Poliscope-${process.platform}-${process.arch}/poliscope${process.platform === 'win32' ? '.exe' : ''}`);

test('WP-029 packaged keyboard matrix direction source choice account trace filters and bounded pages', async () => {
  test.setTimeout(180000);
  const directory = await mkdtemp(join(tmpdir(), 'poliscope-matrix-ui-'));
  const worlds = join(directory, 'worlds'); await mkdir(worlds);
  const seed = spawnSync(resolve('.venv/bin/python'), ['tests/engine/overview_fixture.py', worlds], { encoding: 'utf8' });
  expect(seed.status, seed.stderr).toBe(0);
  const env: Record<string, string | undefined> = { ...process.env, POLISCOPE_USER_DATA: join(directory, 'app') }; delete env.ELECTRON_RUN_AS_NODE;
  const app = await electron.launch({ executablePath, args: ['--no-sandbox'], env: env as Record<string,string> });
  try {
    const page = await app.firstWindow(); await expect(page.getByRole('status')).toHaveText('Local engine ready');
    await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }); }, worlds);
    await page.getByRole('button', { name: 'Choose sandbox folder' }).press('Enter');
    await page.getByLabel('Open civilization and branch').selectOption('civ/main');
    await page.getByRole('button', { name: 'Dependency matrix', exact: true }).focus(); await page.keyboard.press('Enter');
    const matrix = page.getByRole('region', { name: 'Sparse relationship matrix' });
    await expect(matrix).toContainText('not independence');
    await matrix.getByLabel('Matrix grouping').selectOption('scope');
    await matrix.getByLabel('Relationship type', { exact: true }).selectOption('requires');
    await expect(matrix.getByRole('table')).toContainText('requires');
    await expect(matrix.locator('ol > li')).toHaveCount(10);
    await matrix.getByRole('button', { name: 'Next relationship page' }).focus(); await page.keyboard.press('Enter');
    await expect(matrix.getByRole('button', { name: 'Previous relationship page' })).toBeEnabled();
    await matrix.getByRole('button', { name: 'Previous relationship page' }).press('Enter');
    await matrix.getByRole('button', { name: 'node:claim/a/synthetic:claim → node:account/stock · requires', exact: true }).focus(); await page.keyboard.press('Enter');
    const detail = matrix.getByRole('region', { name: 'Relationship details' });
    await expect(detail).toBeFocused();
    await expect(detail).toContainText('Numerical relationship magnitude: Not recorded');
    await detail.getByRole('button', { name: 'Inspect mechanism synthetic:demand', exact: true }).press('Enter');
    await expect(detail.getByRole('region', { name: 'Retained mechanism or rule' })).toContainText('economy');
    await detail.getByRole('button', { name: 'Inspect accounts stock', exact: true }).press('Enter');
    const inspector = matrix.getByRole('complementary', { name: 'Evidence inspector' });
    await expect(inspector).toContainText('Account: stock');
    await expect(inspector.getByRole('table', { name: 'Exact reconciled account' })).toContainText('0');
    await inspector.getByRole('button', { name: /^Open calculation/ }).press('Enter');
    await expect(inspector.getByRole('table', { name: 'Typed inputs and calculated results' }).first()).toBeVisible();
    await inspector.getByRole('button', { name: 'Close evidence inspector' }).press('Enter');
    await detail.getByRole('button', { name: /^Inspect traces/ }).first().press('Enter');
    await expect(inspector.getByRole('table', { name: 'Typed inputs and calculated results' }).first()).toBeVisible();
    await page.getByRole('button', { name: 'History and comparison', exact: true }).press('Enter');
    await page.getByRole('button', { name: 'Dependency matrix', exact: true }).press('Enter');
    await expect(matrix.getByLabel('Relationship type', { exact: true })).toHaveValue('requires');
    await matrix.getByRole('button', { name: 'Clear matrix filters' }).press('Enter');
    await matrix.getByLabel('Relationship type', { exact: true }).selectOption('supersedes');
    await expect(matrix).toContainText('1 recorded relationships');
    await matrix.locator('ol > li button').press('Enter');
    await expect(detail).toContainText('Documentary supersession');
    await detail.getByRole('button', { name: /^Inspect relationship source/ }).press('Enter');
    await expect(detail.getByRole('region', { name: 'Archived source' })).toContainText('9ff539997dbd1bd3fa99deabcf6bc5907602df60');
    await detail.getByRole('button', { name: 'Open participating choice society:DEC-003', exact: true }).press('Enter');
    await expect(page.getByRole('region', { name: 'Selected domain' })).toBeFocused();
    await expect(page.getByRole('region', { name: 'Domain interview' })).toContainText('society:DEC-003');
    await matrix.getByLabel('Relationship provenance', { exact: true }).selectOption('retained_execution');
    await expect(matrix).toContainText('No recorded relationships match these filters.');
    await page.screenshot({ path: '/tmp/poliscope-matrix.png', fullPage: true });
  } finally { await app.close(); await rm(directory, { recursive: true, force: true }); }
});
