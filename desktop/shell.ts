import type { TimelineRequest, TimelineReply } from '../contracts/timeline-workspace';
import type { WorkbenchQuery, WorkbenchPage, WorkbenchEdit, WorkbenchPreview, DeleteNote, DeleteNoteReply } from '../contracts/workbench';
import type { ExplorationQuery, ExplorationPage, ExplorationEdit, ExplorationPreview } from '../contracts/exploration';
import type { MatrixQuery, MatrixPage, MatrixModelQuery, MatrixModelReply } from '../contracts/matrix';
import type { AtlasQuery, AtlasPage, AtlasSourceQuery, AtlasSourcePage } from '../contracts/atlas';
import type { RationaleQuery, RationaleReply, LineageQuery, LineagePage, HistoryAction, CompareQuery, ComparePage } from '../contracts/comparison';
import type { OverviewQuery, OverviewPage, TargetQuery, TargetReply, ChartQuery, ChartReply } from '../contracts/overview';
import type { InterviewQuery, InterviewQuestion, InterviewEdit, InterviewPreview, InterviewApply, InterviewCommit } from '../contracts/interview';
import type { CreateOptions, WorkspaceCatalogue, WorkspaceSelection, WorkspaceState, WorkspacePageRequest, WorkspacePage } from '../contracts/workspace';
import type { HistoryRequest, HistoryResult, HistoryError } from '../contracts/history';
export type ShellStatus = { state: 'starting' | 'ready' | 'failed' | 'historical'; detail: string };
export type HistorySelection = { storage_context_id: string; request: HistoryRequest };
export type HistoryReply = HistoryResult | HistoryError | null;
export interface ShellAPI {
  timeline(query: TimelineRequest): Promise<TimelineReply>;
  workbench(query: WorkbenchQuery): Promise<WorkbenchPage>;
  previewWorkbench(edit: WorkbenchEdit): Promise<WorkbenchPreview>;
  applyWorkbench(candidate: InterviewApply): Promise<InterviewCommit>;
  cancelWorkbench(): Promise<void>;
  deleteNote(query: DeleteNote): Promise<DeleteNoteReply>;
  exploration(query: ExplorationQuery): Promise<ExplorationPage>;
  previewWorld(edit: ExplorationEdit): Promise<ExplorationPreview>;
  applyWorld(candidate: InterviewApply): Promise<InterviewCommit>;
  cancelWorld(): Promise<void>;
  matrixModel(query: MatrixModelQuery): Promise<MatrixModelReply>;
  matrix(query: MatrixQuery): Promise<MatrixPage>;
  atlas(query: AtlasQuery): Promise<AtlasPage>;
  atlasSource(query: AtlasSourceQuery): Promise<AtlasSourcePage>;
  rationale(query: RationaleQuery): Promise<RationaleReply>;
  lineage(query: LineageQuery): Promise<LineagePage>;
  compare(query: CompareQuery): Promise<ComparePage>;
  historyAction(query: HistoryAction): Promise<WorkspaceState>;
  overview(query: OverviewQuery): Promise<OverviewPage>;
  target(query: TargetQuery): Promise<TargetReply>;
  chart(query: ChartQuery): Promise<ChartReply>;
  interview(query: InterviewQuery): Promise<InterviewQuestion>;
  previewInterview(edit: InterviewEdit): Promise<InterviewPreview>;
  applyInterview(candidate: InterviewApply): Promise<InterviewCommit>;
  cancelInterview(): Promise<void>;
  chooseWorkspace(): Promise<WorkspaceCatalogue | null>;
  workspaceCatalogue(): Promise<WorkspaceCatalogue>;
  createWorld(options: CreateOptions): Promise<WorkspaceState>;
  selectWorld(selection: WorkspaceSelection): Promise<WorkspaceState>;
  worldPage(request: WorkspacePageRequest): Promise<WorkspacePage>;
  bootstrapStatus(): Promise<ShellStatus>;
  openHistory(selection: HistorySelection): Promise<HistoryReply>;
  historyPage(collection: HistoryRequest['collection'], offset: number): Promise<HistoryReply>;
  reconnect(): Promise<void>;
}
